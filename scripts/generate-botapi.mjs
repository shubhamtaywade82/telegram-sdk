#!/usr/bin/env node
/**
 * Generates the typed Bot API surface from a committed snapshot.
 *
 *   node scripts/generate-botapi.mjs                 # regenerate src/botapi/generated/*
 *   node scripts/generate-botapi.mjs --check         # exit 1 if the committed output is stale
 *
 * Input : schema/bot-api/bot-api-<version>.json   (produced by scripts/fetch-botapi.mjs)
 * Output: src/botapi/generated/types.ts      interfaces for every Bot API object
 *         src/botapi/generated/methods.ts    parameter and result types per method
 *         src/botapi/generated/client.ts     one typed method per Bot API method
 * The output is deterministic: the same snapshot always produces byte-identical files.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

function snapshotFile() {
  const dir = join(root, 'schema/bot-api');
  const files = readdirSync(dir).filter((f) => /^bot-api-\d+\.\d+\.json$/.test(f)).sort();
  if (files.length === 0) throw new Error('no schema/bot-api/bot-api-<version>.json snapshot found');
  return files[files.length - 1];
}

const PRIMITIVES = {
  String: 'string',
  Integer: 'number',
  Int: 'number',
  Float: 'number',
  'Float number': 'number',
  Boolean: 'boolean',
  True: 'true',
};

/** "A, B, ..., or C", "A or B", "A and B" -> alternatives. */
const splitAlternatives = (expr) =>
  expr
    .split(/\s*,\s*(?:(?:or|and)\s+)?|\s+(?:or|and)\s+/)
    .map((s) => s.trim())
    .filter(Boolean);

/**
 * Maps a Bot API type expression to TypeScript. `prefix` qualifies named types
 * when the output lives in another module (e.g. 'Types.' inside methods.ts).
 */
function makeTsFor(typeNames) {
  return function tsFor(expr, where, prefix = '') {
    const e = expr.trim();
    if (/^Array of /.test(e)) {
      return `Array<${tsFor(e.slice('Array of '.length), where, prefix)}>`;
    }
    const alts = splitAlternatives(e);
    if (alts.length > 1) return alts.map((a) => tsFor(a, where, prefix)).join(' | ');
    if (Object.hasOwn(PRIMITIVES, e)) return PRIMITIVES[e];
    if (e === 'InputFile') return `${prefix}InputFile`;
    if (typeNames.has(e)) return `${prefix}${e}`;
    throw new Error(`unknown Bot API type "${e}" (${where})`);
  };
}

/**
 * The docs label some fields plain "String" while also documenting multipart upload
 * through attach://. Those fields accept a file, so they are widened to "InputFile or String".
 * Each widening is counted and reported, so it cannot happen silently.
 */
const UPLOAD_DOC = /multipart\/form-data|attach:\/\//i;
function effectiveType(type, description, counter) {
  if (type === 'String' && UPLOAD_DOC.test(description ?? '')) {
    counter.widened += 1;
    return 'InputFile or String';
  }
  return type;
}

function jsDoc(text, indent = '') {
  const body = String(text ?? '')
    .replace(/\*\//g, '*\\/')
    .replace(/@(?=[A-Za-z])/g, '\\@') // TypeDoc reads a bare @word as a block tag
    .replace(/\s+/g, ' ')
    .trim();
  if (!body) return '';
  const lines = body.match(/.{1,92}(?=\s|$)/g) ?? [body];
  return [`${indent}/**`, ...lines.map((l) => `${indent} * ${l.trim()}`), `${indent} */`, ''].join('\n');
}

const pascal = (s) => `${s[0].toUpperCase()}${s.slice(1)}`;
const paramsName = (method) => `${pascal(method)}Params`;

function generate(snap, snapFile, counter) {
  const typeNames = new Set(snap.types.map((t) => t.name));
  const tsFor = makeTsFor(typeNames);
  const header =
    `// GENERATED by scripts/generate-botapi.mjs from schema/bot-api/${snapFile}.\n` +
    `// Bot API ${snap.botApiVersion} (${snap.releaseDate}). Do not edit by hand; run \`npm run generate:botapi\`.\n`;

  // types.ts
  const typeBlocks = [];
  for (const t of snap.types) {
    if (t.name === 'InputFile') continue; // provided by the runtime (src/botapi/input-file.ts)
    const doc = jsDoc(t.description);
    if (t.union) {
      const members = t.union.map((u) => tsFor(u, `${t.name} member`));
      typeBlocks.push(`${doc}export type ${t.name} = ${members.join(' | ')};\n`);
    } else if (t.fields.length > 0) {
      const fields = t.fields.map(
        (f) =>
          `${jsDoc(f.description, '  ')}  ${f.name}${f.optional ? '?' : ''}: ${tsFor(effectiveType(f.type, f.description, counter), `${t.name}.${f.name}`)};\n`,
      );
      typeBlocks.push(`${doc}export interface ${t.name} {\n${fields.join('\n')}}\n`);
    } else {
      typeBlocks.push(`${doc}export type ${t.name} = Record<string, never>;\n`);
    }
  }
  const typesTs =
    `${header}\nimport type { InputFile } from '../input-file.js';\nexport type { InputFile };\n\n` +
    typeBlocks.join('\n');

  // methods.ts
  const paramBlocks = [];
  const mapLines = [];
  for (const m of snap.methods) {
    const result = tsFor(m.returns, `${m.name} result`, 'Types.');
    let params = 'EmptyParams';
    if (m.params.length > 0) {
      params = paramsName(m.name);
      const lines = m.params.map(
        (p) =>
          `${jsDoc(p.description, '  ')}  ${p.name}${p.required ? '' : '?'}: ${tsFor(effectiveType(p.type, p.description, counter), `${m.name}.${p.name}`, 'Types.')};\n`,
      );
      paramBlocks.push(`${jsDoc(m.description)}export interface ${params} {\n${lines.join('\n')}}\n`);
    }
    mapLines.push(`  ${m.name}: { params: ${params}; result: ${result} };`);
  }
  const methodsTs =
    `${header}\nimport type * as Types from './types.js';\n\n` +
    `/** Parameters of methods that take no arguments. */\nexport type EmptyParams = Record<string, never>;\n\n` +
    `export const BOT_API_VERSION = ${JSON.stringify(snap.botApiVersion)} as const;\n\n` +
    paramBlocks.join('\n') +
    `\n/** Parameter and result types for every Bot API method. */\n` +
    `export interface BotApiMethodMap {\n${mapLines.join('\n')}\n}\n\n` +
    `export type BotApiMethodName = keyof BotApiMethodMap;\n`;

  // client.ts
  const clientMethods = snap.methods.map((m) => {
    const hasParams = m.params.length > 0;
    const required = m.params.some((p) => p.required);
    const sig = hasParams ? `${required ? 'params' : 'params?'}: Methods.${paramsName(m.name)}` : '';
    const arg = hasParams ? 'params ?? {}' : '{}';
    const ret = tsFor(m.returns, `${m.name} result`, 'Types.');
    return `${jsDoc(m.description, '  ')}  ${m.name}(${sig}): Promise<${ret}> {\n    return this.call('${m.name}', ${arg});\n  }\n`;
  });
  const clientTs =
    `${header}\nimport type * as Types from './types.js';\n` +
    `import type * as Methods from './methods.js';\n` +
    `import { BotApiTransport } from '../transport.js';\n\n` +
    `/** Typed Bot API client: one method per Bot API method, with exact parameter and result types. */\n` +
    `export class BotApiHttpClient extends BotApiTransport {\n${clientMethods.join('\n')}}\n`;

  return { 'types.ts': typesTs, 'methods.ts': methodsTs, 'client.ts': clientTs };
}

function main() {
  const file = snapshotFile();
  const snap = JSON.parse(readFileSync(join(root, 'schema/bot-api', file), 'utf8'));
  const outDir = join(root, 'src/botapi/generated');
  const counter = { widened: 0 };
  const files = generate(snap, file, counter);
  console.log(`widened ${counter.widened} String field(s) documented as accepting uploads to InputFile or String`);
  let stale = false;
  if (!checkOnly) mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const path = join(outDir, name);
    const body = content.endsWith('\n') ? content : `${content}\n`;
    if (checkOnly) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== body) {
        console.error(`stale: ${path}`);
        stale = true;
      }
    } else {
      writeFileSync(path, body);
    }
  }
  if (checkOnly) {
    if (stale) {
      console.error('generated Bot API sources are stale; run `npm run generate:botapi`');
      process.exitCode = 1;
    } else {
      console.log('generated Bot API sources are up to date');
    }
  } else {
    console.log(`generated ${snap.counts.types} types and ${snap.counts.methods} methods from Bot API ${snap.botApiVersion}`);
  }
}

main();
